# Visual contract for four-column native SVG and split gene/cancer workflows.
source("R/fractal.R")
stopifnot(length(make_demo_records()) == 4L)
css <- paste(readLines("www/styles.css", warn = FALSE), collapse = "\n")
app <- paste(readLines("app.R", warn = FALSE), collapse = "\n")
stopifnot(grepl("grid-template-columns:repeat(4,minmax(0,1fr))", css, fixed = TRUE))
stopifnot(grepl("grid-auto-flow:row", css, fixed = TRUE))
stopifnot(grepl("aspect-ratio:1 / 1", css, fixed = TRUE))
stopifnot(grepl("svg_panel(", app, fixed = TRUE))
stopifnot(!grepl("renderPlotly(", app, fixed = TRUE))
stopifnot(grepl('shiny::includeCSS("www/styles.css")', app, fixed = TRUE))
stopifnot(grepl('uiOutput("gene_atlas")', app, fixed = TRUE))
stopifnot(grepl('uiOutput("cancer_atlas")', app, fixed = TRUE))
stopifnot(grepl('input.workspace == \'gene\'', app, fixed = TRUE))
stopifnot(grepl('input.workspace == \'cancer\'', app, fixed = TRUE))
stopifnot(grepl('"1 Mb" = 1000000', app, fixed = TRUE))
stopifnot(grepl('"Tumor − normal: |Δβ| cutoff"', app, fixed = TRUE))
cat("Four-column SVG and separate gene/cancer layouts passed static checks.\n")
